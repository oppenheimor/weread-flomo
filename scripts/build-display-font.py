"""Build frequency-ordered WOFF2 subsets with content-addressed filenames.
Run: uv run --with 'fonttools[woff]==4.61.1' --with 'wordfreq==3.1.1' python scripts/build-display-font.py
The source font is never shipped by Vite. Legacy WOFF files stay available for
clients with the previous CSS cached; current CSS only references hashed WOFF2.
"""
from pathlib import Path
import hashlib
import io
import logging
import re
import sys
from fontTools.ttLib import TTFont
from fontTools import subset
from wordfreq import top_n_list

ROOT = Path(__file__).resolve().parent.parent
SOURCE = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'assets/fonts/QuanZiKuZhengKaiTi.ttf'
OUT = ROOT / 'public/assets/fonts/quanzi-kai'
OUT.mkdir(parents=True, exist_ok=True)
logging.getLogger('fontTools.subset').setLevel(logging.ERROR)
source_bytes = SOURCE.read_bytes()
with TTFont(io.BytesIO(source_bytes)) as font:
    if font['OS/2'].fsType & (0x2 | 0x100 | 0x200):
        raise SystemExit('Font embedding/subsetting restrictions require review.')
    chinese_ranges = [(0x3000, 0x303F), (0x3400, 0x4DBF), (0x4E00, 0x9FFF),
                      (0xF900, 0xFAFF), (0x20000, 0x323AF)]
    cmap = {cp for cp in font.getBestCmap()
            if any(start <= cp <= end for start, end in chinese_ranges)}

# Only actual display headings belong in the tiny critical subset, not every
# Chinese string in the source code. Book-title characters load on demand.
core = {ord(c) for c in '拾墨我的书架账号设置登录注册未同步已同步需核对'} & cmap
ordered = []
seen = set(core)
# A fixed public frequency corpus, never users' private book titles or notes.
for word in top_n_list('zh', 50000):
    for char in word:
        cp = ord(char)
        if cp in cmap and cp not in seen:
            ordered.append(cp)
            seen.add(cp)
common = ordered[:6000]
rare = sorted(cmap - core - set(common))
parts = [('core', core)]
parts += [(f'common-{i // 64:03d}', set(common[i:i + 64])) for i in range(0, len(common), 64)]
parts += [(f'rare-{i // 128:03d}', set(rare[i:i + 128])) for i in range(0, len(rare), 128)]

def ranges(points):
    spans = []
    start = end = None
    for cp in sorted(points):
        if end is not None and cp == end + 1:
            end = cp
        else:
            if start is not None:
                spans.append(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}')
            start = end = cp
    if start is not None:
        spans.append(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}')
    return ','.join(spans)

rules = ['/* Generated by scripts/build-display-font.py; do not edit by hand. */']
expected = set()
covered = set()
for index, (name, points) in enumerate(parts):
    assert not (points & covered), 'Overlapping unicode ranges'
    covered.update(points)
    with TTFont(io.BytesIO(source_bytes), recalcTimestamp=False) as part:
        options = subset.Options()
        options.recalc_timestamp = False
        job = subset.Subsetter(options=options)
        job.populate(unicodes=points)
        job.subset(part)
        part.flavor = 'woff2'
        buffer = io.BytesIO()
        part.save(buffer)
    data = buffer.getvalue()
    filename = f'{name}.{hashlib.sha256(data).hexdigest()[:12]}.woff2'
    expected.add(filename)
    (OUT / filename).write_bytes(data)
    rules.append('@font-face {\n  font-family: "QuanZiKai";\n'
                 f'  src: url("/assets/fonts/quanzi-kai/{filename}") format("woff2");\n'
                 '  font-weight: 400;\n  font-style: normal;\n  font-display: swap;\n'
                 f'  unicode-range: {ranges(points)};\n}}')
    if index == 0 or index % 50 == 0:
        print(f'{index + 1}/{len(parts)} {filename}: {len(data)} bytes', flush=True)
assert covered == cmap, 'Font coverage changed'
(ROOT / 'web/fonts.css').write_text('\n\n'.join(rules) + '\n')
core_file = next(filename for filename in expected if filename.startswith('core.'))
preload = f'<link id="display-font-core" rel="preload" as="font" type="font/woff2" crossorigin href="/assets/fonts/quanzi-kai/{core_file}" />'
index_path = ROOT / 'index.html'
html = index_path.read_text()
if 'id="display-font-core"' in html:
    html = re.sub(r'<link id="display-font-core"[^>]*>', preload, html)
else:
    html = html.replace('    <title>', f'    {preload}\n    <title>')
index_path.write_text(html)
# Do not remove old hashed files automatically: older deployed CSS may still
# reference them. File cleanup must follow the deployment retention policy.
print(f'{len(parts)} subsets; {len(cmap)} characters covered; {sum((OUT / f).stat().st_size for f in expected)} bytes total.')
