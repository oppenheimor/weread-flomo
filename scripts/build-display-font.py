"""Generate locally hosted, on-demand WOFF subsets. Requires fonttools.
Usage: python3 scripts/build-display-font.py [source.ttf]
The original font stays outside public/ and is never shipped by Vite.
"""
from pathlib import Path
import copy
import logging
import sys
from fontTools.ttLib import TTFont
from fontTools import subset

ROOT = Path(__file__).resolve().parent.parent
SOURCE = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'assets/fonts/QuanZiKuZhengKaiTi.ttf'
OUT = ROOT / 'public/assets/fonts/quanzi-kai'
OUT.mkdir(parents=True, exist_ok=True)
logging.getLogger('fontTools.subset').setLevel(logging.ERROR)
font = TTFont(SOURCE)
if font['OS/2'].fsType & (0x2 | 0x100 | 0x200):
    raise SystemExit('Font embedding/subsetting restrictions require review.')
# Only Han characters and Chinese punctuation use Kai. Latin, digits and
# other scripts fall through to the UI font, including inside mixed titles.
chinese_ranges = [(0x3000, 0x303F), (0x3400, 0x4DBF), (0x4E00, 0x9FFF),
                  (0xF900, 0xFAFF), (0x20000, 0x323AF)]
cmap = {cp for cp in font.getBestCmap()
        if any(start <= cp <= end for start, end in chinese_ranges)}
# Bundle UI characters together; arbitrary book titles load additional blocks as needed.
ui = ''.join(path.read_text() for path in (ROOT / 'web').glob('*.tsx'))
core = {ord(c) for c in ui} & cmap
blocks = {}
for cp in sorted(cmap - core):
    blocks.setdefault(cp // 512, set()).add(cp)

def ranges(points):
    spans = []
    start = end = None
    for cp in sorted(points):
        if end is not None and cp == end + 1:
            end = cp
        else:
            if start is not None:
                spans.append(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}')
            start = end = cp
    if start is not None:
        spans.append(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}')
    return ','.join(spans)

rules = ['/* Generated by scripts/build-display-font.py; do not edit by hand. */']
parts = [('core', core)] + [(f'block-{key:04x}', value) for key, value in sorted(blocks.items())]
for name, points in parts:
    part = copy.deepcopy(font)
    options = subset.Options()
    options.flavor = 'woff'
    options.recalc_timestamp = False
    job = subset.Subsetter(options=options)
    job.populate(unicodes=points)
    job.subset(part)
    part.flavor = 'woff'
    part.save(OUT / f'{name}.woff')
    rules.append('@font-face {\n  font-family: "QuanZiKai";\n'
                 f'  src: url("/assets/fonts/quanzi-kai/{name}.woff") format("woff");\n'
                 '  font-weight: 400;\n  font-style: normal;\n  font-display: swap;\n'
                 f'  unicode-range: {ranges(points)};\n}}')
(ROOT / 'web/fonts.css').write_text('\n\n'.join(rules) + '\n')
expected = {f'{name}.woff' for name, _ in parts}
for stale in OUT.glob('block-*.woff'):
    if stale.name not in expected:
        stale.unlink()
print(f'{len(blocks) + 1} subsets; core {(OUT / "core.woff").stat().st_size // 1024} KiB; {len(cmap)} characters covered.')
